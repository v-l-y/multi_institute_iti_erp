CREATE TABLE lesson_plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 institute_id BIGINT UNSIGNED NOT NULL,
 batch_year_id BIGINT UNSIGNED NOT NULL,
 batch_id BIGINT UNSIGNED NOT NULL,
 curriculum_year_id BIGINT UNSIGNED NOT NULL,
 learning_outcome_id BIGINT UNSIGNED NOT NULL,
 instructor_id BIGINT UNSIGNED NOT NULL,
 session_date DATE NOT NULL,
 component ENUM('trade_practical','trade_theory','employability','ojt_project') NOT NULL,
 activity_type ENUM('lesson','demonstration','practical') NOT NULL,
 title VARCHAR(190) NOT NULL,
 instructions TEXT NOT NULL,
 start_minute SMALLINT UNSIGNED NOT NULL,
 planned_minutes SMALLINT UNSIGNED NOT NULL,
 status ENUM('draft','approved') NOT NULL DEFAULT 'draft',
 created_by BIGINT UNSIGNED NOT NULL,
 approved_by BIGINT UNSIGNED NULL,
 approved_at DATETIME NULL,
 review_reference VARCHAR(190) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,institute_id),
 UNIQUE(id,batch_year_id,batch_id,institute_id),
 INDEX(institute_id,batch_year_id,session_date,id),
 FOREIGN KEY(batch_year_id,batch_id,institute_id) REFERENCES batch_years(id,batch_id,institute_id),
 FOREIGN KEY(batch_year_id,curriculum_year_id,institute_id) REFERENCES batch_years(id,curriculum_year_id,institute_id),
 FOREIGN KEY(learning_outcome_id,curriculum_year_id,institute_id) REFERENCES learning_outcomes(id,curriculum_year_id,institute_id),
 FOREIGN KEY(batch_year_id,session_date,component,institute_id) REFERENCES training_calendar_entries(batch_year_id,session_date,component,institute_id),
 FOREIGN KEY(instructor_id,institute_id) REFERENCES staff(id,institute_id),
 FOREIGN KEY(created_by,institute_id) REFERENCES auth_users(id,institute_id),
 FOREIGN KEY(approved_by,institute_id) REFERENCES auth_users(id,institute_id),
 CHECK(planned_minutes>0 AND start_minute+planned_minutes<=1440),
 CHECK(status='draft' OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND review_reference IS NOT NULL AND approved_by<>created_by))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
