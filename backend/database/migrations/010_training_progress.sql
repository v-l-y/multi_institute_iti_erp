CREATE TABLE training_progress (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 institute_id BIGINT UNSIGNED NOT NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 batch_year_id BIGINT UNSIGNED NOT NULL,
 batch_id BIGINT UNSIGNED NOT NULL,
 enrollment_id BIGINT UNSIGNED NOT NULL,
 progress_status ENUM('started','practised','completed') NOT NULL,
 attended_minutes SMALLINT UNSIGNED NOT NULL,
 recorded_on DATE NOT NULL,
 evidence_reference VARCHAR(190) NOT NULL,
 notes TEXT NOT NULL,
 recorded_by BIGINT UNSIGNED NOT NULL,
 supersedes_id BIGINT UNSIGNED NULL,
 correction_reason TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,plan_id,enrollment_id,institute_id),
 UNIQUE(supersedes_id),
 UNIQUE(plan_id,enrollment_id,evidence_reference,institute_id),
 INDEX(institute_id,enrollment_id,id),
 FOREIGN KEY(plan_id,batch_year_id,batch_id,institute_id) REFERENCES lesson_plans(id,batch_year_id,batch_id,institute_id),
 FOREIGN KEY(enrollment_id,batch_id,institute_id) REFERENCES enrollments(id,batch_id,institute_id),
 FOREIGN KEY(recorded_by,institute_id) REFERENCES auth_users(id,institute_id),
 FOREIGN KEY(supersedes_id,plan_id,enrollment_id,institute_id) REFERENCES training_progress(id,plan_id,enrollment_id,institute_id),
 CHECK(attended_minutes>0),
 CHECK(supersedes_id IS NULL OR correction_reason IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
